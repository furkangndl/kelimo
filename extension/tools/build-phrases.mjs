// Builds src/phrases.js: English multiword expressions taken from Wiktionary category listings.
// Wiktionary text is available under CC BY-SA 4.0 / GFDL (https://en.wiktionary.org/wiki/Wiktionary:Copyrights).
// Usage: node tools/build-phrases.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const HEADER = '// Generated by tools/build-phrases.mjs from Wiktionary category listings (CC BY-SA 4.0). Do not edit by hand.\n';
const API = 'https://en.wiktionary.org/w/api.php';
// Longest allowed phrase (in words) per category; the huge "multiword terms" list is limited to short compounds.
const CATEGORIES = {
  'English idioms': 6,
  'English phrasal verbs': 6,
  'English phrases': 6,
  'English prepositional phrases': 6,
  'English proverbs': 6,
  'English multiword terms': 3,
};
const PLACEHOLDERS = /\b(someone|something|somebody|one's|oneself|someone's|somebody's)\b/;
const MIN_WORDS = 2;

// Very common function words: a short phrase made only of these is not a unit worth merging ("and how", "go to").
const CORE_WORDS = new Set(
  `the a an and or but if so to of in on at by for with from up out as is are was were be been am do does did done have has had go goes went i you he she it we they me him her us them my your his its our their this that these those what who how when where why which not no yes can could will would should may might must there here then than just all one same very much many more most some any such`.split(
    ' ',
  ),
);

const isNoise = (phrase) => {
  const words = phrase.split(' ');
  return words.length <= 3 && words.every((word) => CORE_WORDS.has(word));
};

const sleep = (ms) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

function request(params) {
  const url = `${API}?${new URLSearchParams({ action: 'query', format: 'json', ...params })}`;
  for (let attempt = 1; ; attempt++) {
    try {
      const body = execFileSync('curl', ['-s', '--fail', '-A', 'KelimoPhraseBuilder/1.0 (https://kelimo.net; open-source language learning project)', url], {
        maxBuffer: 64 * 1024 * 1024,
      });
      sleep(500);
      return JSON.parse(body.toString());
    } catch (error) {
      if (attempt >= 5) {
        throw error;
      }
      sleep(3000 * attempt);
    }
  }
}

function categoryTitles(category) {
  const titles = [];
  let cont = {};
  do {
    const data = request({ list: 'categorymembers', cmtitle: `Category:${category}`, cmlimit: '500', cmnamespace: '0', ...cont });
    titles.push(...data.query.categorymembers.map((member) => member.title));
    cont = data.continue ?? null;
  } while (cont);
  return titles;
}

if (process.argv.includes('--filter-only')) {
  // Re-apply the noise filter to the already generated src/phrases.js without downloading again.
  const sandbox = {};
  new Function('globalThis', readFileSync('src/phrases.js', 'utf8'))(sandbox);
  const all = [...sandbox.KELIMO_PHRASES];
  const kept = all.filter((phrase) => !isNoise(phrase)).sort();
  writeFileSync('src/phrases.js', `${HEADER}globalThis.KELIMO_PHRASES = new Set(${JSON.stringify(kept.join('\n'))}.split('\\n'));\n`);
  console.log(`filtered ${all.length} -> ${kept.length} phrases`);
  process.exit(0);
}

const phrases = new Set();
for (const [category, maxWords] of Object.entries(CATEGORIES)) {
  const titles = categoryTitles(category);
  let kept = 0;
  for (const title of titles) {
    const words = title.split(' ');
    if (words.length < MIN_WORDS || words.length > maxWords) continue;
    if (!/^[a-z][a-z' -]*$/.test(title) || PLACEHOLDERS.test(title)) continue;
    if (isNoise(title)) continue;
    phrases.add(title);
    kept++;
  }
  console.log(`${category}: ${titles.length} titles, ${kept} kept`);
}

const sorted = [...phrases].sort();
writeFileSync('src/phrases.js', `${HEADER}globalThis.KELIMO_PHRASES = new Set(${JSON.stringify(sorted.join('\n'))}.split('\\n'));\n`);
console.log(`src/phrases.js: ${sorted.length} phrases`);
